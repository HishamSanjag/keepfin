package app.keepfin

import android.content.ComponentName
import android.content.Context
import android.content.pm.PackageManager
import org.json.JSONObject

/** One pre-rendered colour of one icon design: its launcher alias and the mipmap that shows it in the picker. */
data class AppIconAccent(val hex: String, val alias: String, val preview: String)

/** One icon design (id and name come from assets/icons/variants/index.json through assets/app-icons.json; nothing is hard-coded). */
data class AppIconVariant(val id: String, val name: String, val fixedColours: Boolean, val accents: List<AppIconAccent>)

data class AppIconChoice(val id: String, val accent: String)

/** The generated list of icon designs. */
class AppIconCatalog(val mainId: String, val accent: String, val defaultAlias: String, val variants: List<AppIconVariant>) {
    val defaultChoice get() = AppIconChoice(mainId, accent)
    /** Every launcher alias, including the default one. */
    val aliases: List<String> get() = variants.flatMap { v -> v.accents.map { it.alias } }.distinct()

    fun variant(id: String) = variants.firstOrNull { it.id == id }

    /** The colour of [choice]; a design that has no such colour (a fixed-colour design) answers with its own. */
    fun resolve(choice: AppIconChoice): AppIconAccent? {
        val v = variant(choice.id) ?: return null
        return v.accents.firstOrNull { it.hex.equals(choice.accent, true) } ?: v.accents.firstOrNull()
    }

    companion object {
        fun parse(json: String): AppIconCatalog {
            val root = JSONObject(json)
            val icons = root.getJSONArray("icons")
            val variants = (0 until icons.length()).map { i ->
                val v = icons.getJSONObject(i)
                val accents = v.getJSONArray("accents")
                AppIconVariant(
                    v.getString("id"), v.getString("name"), v.optBoolean("fixedColours", false),
                    (0 until accents.length()).map { a ->
                        val o = accents.getJSONObject(a)
                        AppIconAccent(o.getString("hex"), o.getString("alias"), o.getString("preview"))
                    },
                )
            }
            return AppIconCatalog(root.getString("main"), root.getString("accent"), root.getString("defaultAlias"), variants)
        }
    }
}

/** Which launcher entries are enabled, and how to change one. The Android implementation is [PackageManager]; tests use a fake. */
interface LauncherStates {
    fun isEnabled(alias: String): Boolean
    fun set(alias: String, enabled: Boolean)
}

/** What the picker talks to. */
interface AppIconController {
    val catalog: AppIconCatalog
    fun current(): AppIconChoice
    /** Switches the launcher icon and remembers the choice. Returns false when the choice is unknown or the switch failed. */
    fun choose(choice: AppIconChoice): Boolean
}

/**
 * Switching the launcher icon (Settings, Appearance, App icon). Android cannot repaint a launcher icon, so each
 * design/colour is a disabled activity-alias of MainActivity (generated by `npm run icons:build`) and exactly one
 * launcher entry is enabled at a time: the new entry is enabled first, then the old ones are disabled, so there is never
 * a moment without an entry.
 */
class AppIcons(private val catalog0: AppIconCatalog, private val states: LauncherStates, private val store: Store) : AppIconController {
    interface Store { fun read(): AppIconChoice?; fun write(choice: AppIconChoice) }

    override val catalog get() = catalog0

    override fun current(): AppIconChoice = store.read()?.takeIf { catalog0.resolve(it) != null } ?: catalog0.defaultChoice

    override fun choose(choice: AppIconChoice): Boolean {
        val target = catalog0.resolve(choice) ?: return false
        if (!apply(target.alias)) return false
        store.write(AppIconChoice(choice.id, target.hex))
        return true
    }

    /** After an update or a restore the component states can be back at the manifest defaults; make them match the stored choice. */
    fun reconcile(): Boolean = apply((catalog0.resolve(current()) ?: catalog0.resolve(catalog0.defaultChoice))?.alias ?: catalog0.defaultAlias)

    private fun apply(alias: String): Boolean = try {
        for ((name, enable) in plan(catalog0.aliases, alias) { states.isEnabled(it) }) states.set(name, enable)
        true
    } catch (e: Exception) { android.util.Log.w("KeepfinAppIcon", "icon switch failed", e); false }

    companion object {
        /** The changes that leave only [target] enabled: it is enabled first, the others are disabled after. Nothing when already right. */
        fun plan(all: List<String>, target: String, isEnabled: (String) -> Boolean): List<Pair<String, Boolean>> {
            val enable = if (isEnabled(target)) emptyList() else listOf(target to true)
            return enable + all.filter { it != target && isEnabled(it) }.map { it to false }
        }

        private const val PREFS = "app-icon"

        fun load(context: Context): AppIcons? = try {
            val json = context.assets.open("app-icons.json").bufferedReader().use { it.readText() }
            val catalog = AppIconCatalog.parse(json)
            val app = context.applicationContext
            AppIcons(catalog, PackageManagerStates(app, catalog), object : Store {
                private val prefs get() = app.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
                override fun read() = prefs.getString("id", null)?.let { AppIconChoice(it, prefs.getString("accent", "") ?: "") }
                override fun write(choice: AppIconChoice) { prefs.edit().putString("id", choice.id).putString("accent", choice.accent).apply() }
            })
        } catch (e: Exception) { android.util.Log.w("KeepfinAppIcon", "icon catalogue not loaded", e); null }

        /** Called once from [KeepfinApplication.onCreate]. */
        fun reconcile(context: Context) { load(context)?.reconcile() }
    }
}

private class PackageManagerStates(private val context: Context, private val catalog: AppIconCatalog) : LauncherStates {
    private fun component(alias: String) = ComponentName(context.packageName, "app.keepfin" + alias)
    override fun isEnabled(alias: String): Boolean = when (context.packageManager.getComponentEnabledSetting(component(alias))) {
        PackageManager.COMPONENT_ENABLED_STATE_ENABLED -> true
        PackageManager.COMPONENT_ENABLED_STATE_DEFAULT -> alias == catalog.defaultAlias // the manifest enables only the default entry
        else -> false
    }
    override fun set(alias: String, enabled: Boolean) {
        context.packageManager.setComponentEnabledSetting(
            component(alias),
            if (enabled) PackageManager.COMPONENT_ENABLED_STATE_ENABLED else PackageManager.COMPONENT_ENABLED_STATE_DISABLED,
            PackageManager.DONT_KILL_APP,
        )
    }
}

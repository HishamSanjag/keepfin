/** A small drawn picture of what a Keepfin folder is: Music, Videos, Photos and a hidden .keepfin for the library's own data. */
@Composable
internal fun FolderTreePicture(modifier: Modifier = Modifier) {
    val colors = MaterialTheme.colorScheme
    Surface(
        modifier.fillMaxWidth().semantics { contentDescription = "A Keepfin folder holds Music, Videos and Photos, and a hidden .keepfin folder for the library's own data" },
        shape = RoundedCornerShape(16.dp), color = Studio.colors.raised,
        border = if (Studio.colors.dark) null else BorderStroke(1.dp, Studio.colors.separator),
    ) {
        Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(2.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Icon(Icons.Outlined.Folder, contentDescription = null, tint = colors.primary, modifier = Modifier.size(24.dp))
                Text("Keepfin", fontSize = 16.sp, fontWeight = FontWeight.SemiBold)
            }
            val rows: List<Triple<ImageVector, String, Boolean>> = listOf(
                Triple(Icons.Outlined.MusicNote, "Music", false), Triple(Icons.Outlined.Movie, "Videos", false),
                Triple(Icons.Outlined.Image, "Photos", false), Triple(Icons.Outlined.Lock, ".keepfin  (hidden, the library's data)", true),
            )
            rows.forEachIndexed { index, (icon, label, hidden) ->
                Row(Modifier.padding(start = 11.dp).height(32.dp), verticalAlignment = Alignment.CenterVertically) {
                    // the tree branch: a vertical line that stops at the last row, and a short stub to the entry
                    Box(Modifier.width(1.dp).fillMaxHeight(if (index == rows.lastIndex) 0.5f else 1f).background(colors.outlineVariant).align(Alignment.Top))
                    Box(Modifier.width(14.dp).height(1.dp).background(colors.outlineVariant))
                    Spacer(Modifier.width(6.dp))
                    Icon(icon, contentDescription = null, tint = if (hidden) colors.outline else colors.onSurfaceVariant, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.width(8.dp))
                    Text(label, fontSize = 14.sp, color = if (hidden) colors.outline else colors.onSurface, maxLines = 1, overflow = TextOverflow.Ellipsis)
                }
            }
        }
    }
}

/**
 * A large choice card: an icon, a title, one sentence, and a check when it is the selected one. [selected] null means a plain action
 * card (no selection state), true/false a selectable one.
 */
@Composable
internal fun ChoiceCard(
    icon: ImageVector, title: String, hint: String?, onClick: () -> Unit, modifier: Modifier = Modifier,
    selected: Boolean? = null, enabled: Boolean = true, badge: String? = null, tag: String? = null, compact: Boolean = false,
) {
    val colors = MaterialTheme.colorScheme
    val on = selected == true
    val shape = RoundedCornerShape(16.dp)
    val container = if (on) colors.primaryContainer else Studio.colors.raised
    val line = if (on) colors.primary else if (Studio.colors.dark) colors.outlineVariant else Studio.colors.separator
    Surface(
        modifier.then(if (tag != null) Modifier.testTag(tag) else Modifier).heightIn(min = 48.dp)
            .then(
                if (selected == null) Modifier.clickable(enabled = enabled, role = Role.Button, onClick = onClick)
                else Modifier.selectable(selected = on, enabled = enabled, role = Role.RadioButton, onClick = onClick),
            ),
        shape = shape, color = container, border = BorderStroke(if (on) 2.dp else 1.dp, line),
    ) {
        val inner: @Composable () -> Unit = {
            Box(Modifier.size(if (compact) 36.dp else 44.dp).clip(CircleShape).background(if (on) colors.primary else colors.surfaceContainerHigh), contentAlignment = Alignment.Center) {
                Icon(icon, contentDescription = null, tint = if (on) colors.onPrimary else colors.onSurfaceVariant, modifier = Modifier.size(if (compact) 20.dp else 24.dp))
            }
        }
        if (compact) {
            Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    inner()
                    Spacer(Modifier.weight(1f))
                    if (on) Icon(Icons.Outlined.Check, contentDescription = "Selected", tint = colors.primary, modifier = Modifier.size(22.dp))
                }
                Text(title, fontSize = 15.sp, fontWeight = FontWeight.SemiBold, lineHeight = 19.sp)
                if (hint != null) Text(hint, fontSize = 12.sp, lineHeight = 16.sp, color = colors.onSurfaceVariant)
                if (badge != null) Badge(badge)
            }
        } else {
            Row(Modifier.padding(16.dp), verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(14.dp)) {
                inner()
                Column(Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(2.dp)) {
                    Text(title, fontSize = 16.sp, fontWeight = FontWeight.SemiBold)
                    if (hint != null) Text(hint, fontSize = 14.sp, lineHeight = 19.sp, color = colors.onSurfaceVariant)
                    if (badge != null) Badge(badge)
                }
                if (selected == null) Icon(Icons.AutoMirrored.Outlined.KeyboardArrowRight, contentDescription = null, tint = colors.outline)
                else if (on) Icon(Icons.Outlined.Check, contentDescription = "Selected", tint = colors.primary)
            }
        }
    }
}


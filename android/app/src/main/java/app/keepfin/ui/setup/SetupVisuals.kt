/** Steps joined by a line: done ones tick, the current one is filled, the rest are outlined. */
@Composable
internal fun Stepper(steps: List<String>, current: Int, modifier: Modifier = Modifier) {
    val colors = MaterialTheme.colorScheme
    Row(modifier.fillMaxWidth().semantics { contentDescription = "Step ${current + 1} of ${steps.size}: ${steps.getOrNull(current) ?: ""}" }, verticalAlignment = Alignment.Top) {
        steps.forEachIndexed { index, name ->
            val done = index < current
            val now = index == current
            Column(Modifier.weight(1f), horizontalAlignment = Alignment.CenterHorizontally) {
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                    Box(Modifier.weight(1f).height(2.dp).background(if (index == 0) Color.Transparent else if (done || now) colors.primary else colors.outlineVariant))
                    Box(
                        Modifier.size(28.dp).clip(CircleShape).background(if (done || now) colors.primary else Color.Transparent)
                            .then(if (done || now) Modifier else Modifier.background(Color.Transparent)),
                        contentAlignment = Alignment.Center,
                    ) {
                        if (done) Icon(Icons.Outlined.Check, contentDescription = null, tint = colors.onPrimary, modifier = Modifier.size(16.dp))
                        else Text("${index + 1}", fontSize = 12.sp, fontWeight = FontWeight.SemiBold, color = if (now) colors.onPrimary else colors.onSurfaceVariant)
                    }
                    Box(Modifier.weight(1f).height(2.dp).background(if (index == steps.lastIndex) Color.Transparent else if (done) colors.primary else colors.outlineVariant))
                }
                Text(name, fontSize = 12.sp, fontWeight = if (now) FontWeight.SemiBold else FontWeight.Normal, color = if (now) colors.onSurface else colors.onSurfaceVariant, maxLines = 1, modifier = Modifier.padding(top = 4.dp))
            }
        }
    }
}

/** Needed room against the free room: a bar that turns red when the files do not fit. */
@Composable
internal fun SpaceBar(neededBytes: Long, freeBytes: Long?, fits: Boolean, modifier: Modifier = Modifier, format: (Long) -> String) {
    val colors = MaterialTheme.colorScheme
    Column(modifier, verticalArrangement = Arrangement.spacedBy(6.dp)) {
        val fraction = if (freeBytes == null || freeBytes <= 0) 0.02f else (neededBytes.toDouble() / freeBytes).toFloat()
        SizeBar(fraction, color = if (fits) colors.primary else colors.error)
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
            Text("Needs ${format(neededBytes)}", fontSize = 13.sp, color = colors.onSurfaceVariant)
            Text(freeBytes?.let { "${format(it)} free" } ?: "Free space unknown", fontSize = 13.sp, color = colors.onSurfaceVariant)
        }
    }
}

/** What Android will ask after the button: two numbered taps, drawn small. */
@Composable
internal fun ConfirmSteps(modifier: Modifier = Modifier) {
    val colors = MaterialTheme.colorScheme
    Surface(modifier.fillMaxWidth(), shape = RoundedCornerShape(14.dp), color = colors.surfaceContainerHigh) {
        Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
            Text("Android will ask you to confirm. Tap Use this folder, then Allow.", fontSize = 14.sp, lineHeight = 20.sp)
            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf("Use this folder", "Allow").forEachIndexed { i, label ->
                    if (i > 0) Icon(Icons.AutoMirrored.Outlined.ArrowForward, contentDescription = "then", tint = colors.outline, modifier = Modifier.size(16.dp))
                    Surface(shape = RoundedCornerShape(50), color = colors.primaryContainer, contentColor = colors.onPrimaryContainer) {
                        Row(Modifier.padding(horizontal = 10.dp, vertical = 6.dp), verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                            Text("${i + 1}", fontSize = 12.sp, fontWeight = FontWeight.Bold)
                            Text(label, fontSize = 13.sp, fontWeight = FontWeight.SemiBold)
                        }
                    }
                }
            }
        }
    }

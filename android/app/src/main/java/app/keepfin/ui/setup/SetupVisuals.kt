/** A readable place such as "Internal storage > Keepfin" drawn as a breadcrumb of chips. */
@Composable
internal fun Breadcrumb(label: String, modifier: Modifier = Modifier) {
    val parts = label.split(">", "›").map { it.trim() }.filter { it.isNotEmpty() }.ifEmpty { listOf(label) }
    FlowRow(modifier, horizontalArrangement = Arrangement.spacedBy(2.dp), verticalArrangement = Arrangement.spacedBy(4.dp), itemVerticalAlignment = Alignment.CenterVertically) {
        parts.forEachIndexed { index, part ->
            val last = index == parts.lastIndex
            Surface(shape = RoundedCornerShape(8.dp), color = if (last) MaterialTheme.colorScheme.primaryContainer else MaterialTheme.colorScheme.surfaceContainerHigh) {
                Row(Modifier.padding(horizontal = 8.dp, vertical = 4.dp), verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                    if (last) Icon(Icons.Outlined.Folder, contentDescription = null, modifier = Modifier.size(16.dp), tint = MaterialTheme.colorScheme.onPrimaryContainer)
                    Text(part, fontSize = 13.sp, fontWeight = if (last) FontWeight.SemiBold else FontWeight.Normal, color = if (last) MaterialTheme.colorScheme.onPrimaryContainer else MaterialTheme.colorScheme.onSurface, maxLines = 1, overflow = TextOverflow.Ellipsis)
                }
            }
            if (!last) Icon(Icons.AutoMirrored.Outlined.KeyboardArrowRight, contentDescription = null, tint = MaterialTheme.colorScheme.outline, modifier = Modifier.size(18.dp))
        }
    }
}


  await test('back (Alt+Left and the arrow by the breadcrumb) returns to where the list was scrolled', async (page) => {
    await openSpace(page, 'Music')
    await page.getByRole('tab', {name: /^Albums/}).click()
    const albums = libMain(page).getByRole('button', {name: /^Weather Systems/})
    // the panel that scrolls the page, and how far it is scrolled now
    const where = () =>
      albums.evaluate((node) => {
        let el = node.parentElement
        while (el && !(el.scrollHeight > el.clientHeight + 1 && /auto|scroll/.test(getComputedStyle(el).overflowY))) el = el.parentElement
        return el ? el.scrollTop : -1
      })
    for (const back of ['key', 'arrow']) {
      await albums.scrollIntoViewIfNeeded()
      await page.mouse.wheel(0, 2000) // to the end, as a person scrolls
      await page.waitForTimeout(200)
      const before = await where()
      assert.ok(before > 40, `the page is scrolled (${before})`)
      await albums.click()
      await page.getByText('Disc 1').waitFor()
      // the album has the back arrow beside its breadcrumb
      const arrow = page.getByRole('navigation', {name: 'Breadcrumb'}).getByRole('button', {name: 'Back'})
      await arrow.waitFor()
      if (back === 'key') await page.keyboard.press('Alt+ArrowLeft')
      else await arrow.click()
      await albums.waitFor()
      await page.waitForTimeout(300)
      const after = await where()
      assert.ok(Math.abs(after - before) <= 2, `${back}: back on Albums where it was (${before} → ${after})`)
      // and forward opens the album again
      if (back === 'key') {
        await page.keyboard.press('Alt+ArrowRight')
        await page.getByText('Disc 1').waitFor()
        await page.keyboard.press('Alt+ArrowLeft')
        await albums.waitFor()
      }
    }
  }, {width: 1100, height: 420})


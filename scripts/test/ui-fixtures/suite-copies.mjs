    await backup.getByRole('button', {name: 'Restore Glass Harbour.mp3'}).click()
    const restore = await got(page, 'copiesRestore')
    assert.equal(restore.copies.entryId, 'v1')
    await backup.getByRole('button', {name: 'Free up space…'}).click()
    const free = page.getByRole('dialog', {name: 'Free up space on Backup drive (E:)?'})
    await free.getByText('This deletes 14 earlier versions and the 3 files kept after you deleted them from your library from this backup.').waitFor()
    await free.getByText('The backup keeps its copy of everything in your library').waitFor()
    await free.getByRole('button', {name: 'Free up space'}).click()
    await sent(page, 'copiesCleanup')
    await free.waitFor({state: 'detached'})
